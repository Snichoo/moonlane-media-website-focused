// Parses the raw Chromatix homepage HTML and emits cleaned, self-contained
// inner-HTML for each section into src/sections/markup.ts.
// Cleaning: un-lazy images/videos, rewrite asset URLs to the local /wp-content
// mirror, strip scripts/tracking/XML PIs, neutralise form actions.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'node-html-parser';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SCRATCH = 'C:/Users/samsn/AppData/Local/Temp/claude/c--Users-samsn-OneDrive-Desktop-Desktop-AppProjects-Website-New-moonlane-media-website/4a4abe99-e4dc-4489-9a14-fa1d48d8f4d7/scratchpad/ref';

const raw = fs.readFileSync(`${SCRATCH}/index.html`, 'utf8');
const root = parse(raw, { comment: false, blockTextElements: { script: false, noscript: false, style: true, pre: true } });

const rewriteUrl = (u) => u
  .replace(/https?:\/\/www\.chromatix\.com\.au\/wp-content\//g, '/wp-content/')
  .replace(/\/\/www\.chromatix\.com\.au\/wp-content\//g, '/wp-content/');

function clean(el) {
  if (!el) return '';
  // Remove tracking / script / noscript / iframe nodes
  el.querySelectorAll('script, noscript, iframe').forEach(n => n.remove());

  // Un-lazy: promote data-src/data-srcset to real attributes on all elements
  el.querySelectorAll('[data-src], [data-srcset], [data-lazy-src]').forEach(n => {
    const ds = n.getAttribute('data-src');
    const dss = n.getAttribute('data-srcset');
    const dls = n.getAttribute('data-lazy-src');
    if (ds) { n.setAttribute('src', rewriteUrl(ds)); n.removeAttribute('data-src'); }
    if (dls) { n.setAttribute('src', rewriteUrl(dls)); n.removeAttribute('data-lazy-src'); }
    if (dss) { n.setAttribute('srcset', rewriteUrl(dss)); n.removeAttribute('data-srcset'); }
    // drop the lazy class so no external lazy-loader is expected
    const cls = n.getAttribute('class');
    if (cls) n.setAttribute('class', cls.replace(/\blazy\b/g, '').replace(/\s+/g, ' ').trim());
  });

  // Rewrite remaining src / srcset / href / poster that point at the live host's assets
  el.querySelectorAll('[src], [srcset], [poster], [style]').forEach(n => {
    for (const attr of ['src', 'srcset', 'poster', 'style']) {
      const v = n.getAttribute(attr);
      if (v && v.includes('chromatix.com.au/wp-content')) n.setAttribute(attr, rewriteUrl(v));
    }
  });

  // Make videos mobile-friendly + autoplay reliably
  el.querySelectorAll('video').forEach(v => {
    v.setAttribute('playsinline', '');
    v.setAttribute('muted', '');
    v.setAttribute('preload', 'auto');
  });

  // Neutralise forms (no external POST); keep markup for visuals
  el.querySelectorAll('form').forEach(f => { f.setAttribute('action', '#'); f.setAttribute('onsubmit', 'return false;'); });

  // Strip inline event handlers (except the form guard above is removed too — behaviours re-added in React)
  el.querySelectorAll('*').forEach(n => {
    for (const a of Object.keys(n.attributes)) {
      if (/^on/i.test(a) && n.tagName !== 'FORM') n.removeAttribute(a);
    }
  });

  let html = el.innerHTML;
  // Remove XML processing instructions left inside inline SVGs
  html = html.replace(/<\?xml[^>]*\?>/g, '');
  // Any stray absolute host refs (non wp-content) left pointing at live site are harmless; leave nav links intact.
  return html.trim();
}

const sel = (s) => root.querySelector(s);

const sections = {
  header:        clean(sel('#chr-header')),
  sideForm:      clean(sel('.side-form-section')),
  homeBanner:    clean(sel('#home-banner')),
  sectionTwo:    clean(sel('#chr-section-two')),
  ourWork:       clean(sel('#our-work-part')),
  testimonials:  clean(sel('#testimonial-video-slider-section')),
  sectionThree:  clean(sel('#chr-section-three')),
  partners:      clean(sel('#our-partners-part')),
  faq:           clean(sel('#chr-faq-section')),
  footer:        clean(sel('#chr-footer')),
  mobileButton:  clean(sel('.mobile-bottom-button-wrapper')),
};

const outDir = path.join(ROOT, 'src', 'sections');
fs.mkdirSync(outDir, { recursive: true });
let out = '// AUTO-GENERATED by scripts/extract-sections.mjs — cleaned inner HTML of each\n';
out += '// homepage section from the live Chromatix site (assets rewritten to /public mirror).\n\n';
for (const [k, v] of Object.entries(sections)) {
  out += `export const ${k}: string = ${JSON.stringify(v)};\n\n`;
}
fs.writeFileSync(path.join(outDir, 'markup.ts'), out);

// Report
console.log('Section innerHTML sizes (chars):');
for (const [k, v] of Object.entries(sections)) {
  console.log(`  ${k.padEnd(14)} ${v ? v.length : 'MISSING/0'}`);
}
// sanity: leftover lazy attrs or live asset refs
const all = Object.values(sections).join('');
console.log('Leftover data-src:', (all.match(/data-src=/g) || []).length);
console.log('Leftover live wp-content refs:', (all.match(/chromatix\.com\.au\/wp-content/g) || []).length);
console.log('Total video tags:', (all.match(/<video/g) || []).length);
